"""
Jakarta Urban Flood Susceptibility Assessment
GeoAI mini-project workflow (Google Colab)

This script:
1. Initializes Google Earth Engine.
2. Builds Sentinel-2 and terrain predictors for Jakarta.
3. Creates a historical flood inventory from the Global Flood Database.
4. Samples data and trains/evaluates a Random Forest model.
5. Exports predictor rasters to Google Drive.
6. Applies the trained scikit-learn model to the raster.
7. Produces flood probability and susceptibility GeoTIFFs and a PNG map.

Run this in Google Colab. Update EE_PROJECT_ID if your Earth Engine
Cloud Project ID is different.
"""

# If a dependency is missing in Colab, uncomment and run:
# !pip install -q earthengine-api geemap rasterio scikit-learn pandas numpy matplotlib

import os
import time
import shutil
import warnings

import ee
import geemap
import numpy as np
import pandas as pd
import rasterio
import matplotlib.pyplot as plt

from google.colab import drive
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split
from sklearn.metrics import (
    classification_report,
    confusion_matrix,
    roc_auc_score,
    average_precision_score,
)
import joblib


# ---------------------------------------------------------------------
# 1. USER SETTINGS
# ---------------------------------------------------------------------

EE_PROJECT_ID = "sentinel2-data-downlaod"  # Change if required
DRIVE_FOLDER = "GeoAI_Jakarta"
DRIVE_RASTER = f"/content/drive/MyDrive/{DRIVE_FOLDER}/Jakarta_predictors.tif"

WORK_DIR = "/content"
PREDICTOR_RASTER = os.path.join(WORK_DIR, "Jakarta_predictors.tif")
PROBABILITY_RASTER = os.path.join(WORK_DIR, "Jakarta_flood_probability.tif")
SUSCEPTIBILITY_RASTER = os.path.join(WORK_DIR, "Jakarta_flood_susceptibility.tif")
MAP_PNG = os.path.join(WORK_DIR, "Jakarta_flood_susceptibility.png")
MODEL_FILE = os.path.join(WORK_DIR, "Jakarta_random_forest.joblib")

FEATURES = ["elevation", "slope", "NDVI", "NDWI", "NDBI"]
SELECTED_EVENT_COUNT = 10
SAMPLE_COUNT = 3000
SAMPLE_SCALE = 250
CLASSIFICATION_THRESHOLD = 0.30

# Jakarta study area: [west, south, east, north]
JAKARTA = ee.Geometry.Rectangle([106.75, -6.35, 107.00, -6.10])


# ---------------------------------------------------------------------
# 2. INITIALIZE GOOGLE EARTH ENGINE
# ---------------------------------------------------------------------

print("\n[1/8] Authenticating and initializing Google Earth Engine...")
ee.Authenticate()
ee.Initialize(project=EE_PROJECT_ID)
print("Earth Engine initialized.")


# ---------------------------------------------------------------------
# 3. CREATE SATELLITE AND TERRAIN PREDICTORS
# ---------------------------------------------------------------------

print("\n[2/8] Preparing Sentinel-2 and terrain predictors...")

sentinel = (
    ee.ImageCollection("COPERNICUS/S2_SR_HARMONIZED")
    .filterBounds(JAKARTA)
    .filterDate("2025-01-01", "2026-01-01")
    .filter(ee.Filter.lt("CLOUDY_PIXEL_PERCENTAGE", 20))
    .median()
    .clip(JAKARTA)
)

ndvi = sentinel.normalizedDifference(["B8", "B4"]).rename("NDVI")
ndwi = sentinel.normalizedDifference(["B3", "B8"]).rename("NDWI")
ndbi = sentinel.normalizedDifference(["B11", "B8"]).rename("NDBI")

dem = ee.Image("USGS/SRTMGL1_003").clip(JAKARTA)
slope = ee.Terrain.slope(dem).rename("slope")

predictors = (
    dem.rename("elevation")
    .addBands(slope)
    .addBands(ndvi)
    .addBands(ndwi)
    .addBands(ndbi)
)

predictor_image = predictors.select(FEATURES).toFloat()

print("Predictor bands:", predictor_image.bandNames().getInfo())


# ---------------------------------------------------------------------
# 4. BUILD HISTORICAL FLOOD INVENTORY
# ---------------------------------------------------------------------

print("\n[3/8] Searching the Global Flood Database...")

flood_collection = ee.ImageCollection("GLOBAL_FLOOD_DB/MODIS_EVENTS/V1")
jakarta_floods = flood_collection.filterBounds(JAKARTA)
event_count = jakarta_floods.size().getInfo()

print("Historical flood events intersecting the study area:", event_count)

if event_count == 0:
    raise RuntimeError("No Global Flood Database events intersect the Jakarta study area.")

flood_list = jakarta_floods.toList(event_count)
flood_stats = []

for event_id in range(event_count):
    event = ee.Image(flood_list.get(event_id))
    stats = event.select("flooded").reduceRegion(
        reducer=ee.Reducer.sum(),
        geometry=JAKARTA,
        scale=250,
        maxPixels=1e9,
        bestEffort=True,
    ).getInfo()

    flood_stats.append({
        "event_id": event_id,
        "flooded_value_sum": stats.get("flooded"),
    })

flood_stats_df = pd.DataFrame(flood_stats)
flood_stats_df = flood_stats_df.dropna(subset=["flooded_value_sum"])

if flood_stats_df.empty:
    raise RuntimeError("Could not find valid flooded-band values in the intersecting events.")

top_events = flood_stats_df.sort_values(
    "flooded_value_sum", ascending=False
).head(min(SELECTED_EVENT_COUNT, len(flood_stats_df)))

print("\nSelected events (ranked by flooded-band value sum):")
print(top_events.to_string(index=False))

selected_event_images = []
for event_id in top_events["event_id"].astype(int).tolist():
    event = ee.Image(flood_list.get(event_id))
    selected_event_images.append(event.select("flooded"))

# Historical maximum flood extent across selected events.
# Note: interpretation depends on the source masks and observation coverage.
historical_flood = (
    ee.ImageCollection.fromImages(selected_event_images)
    .max()
    .rename("flood")
    .clip(JAKARTA)
)

training_image = predictor_image.addBands(historical_flood)


# ---------------------------------------------------------------------
# 5. SAMPLE DATA AND TRAIN RANDOM FOREST
# ---------------------------------------------------------------------

print("\n[4/8] Sampling training data...")

samples = training_image.sample(
    region=JAKARTA,
    scale=SAMPLE_SCALE,
    numPixels=SAMPLE_COUNT,
    seed=42,
    geometries=False,
    tileScale=4,
)

df = geemap.ee_to_df(samples)
df = df.dropna(subset=FEATURES + ["flood"]).copy()

# Convert the flood label to binary. This assumes the source flood band
# contains 0/1 values. Inspect unique values if this assumption fails.
df["flood"] = (df["flood"] > 0).astype(int)

print("Sample dataset shape:", df.shape)
print("\nFlood distribution:")
print(df["flood"].value_counts())
print("\nFlood percentage:")
print((df["flood"].value_counts(normalize=True) * 100).round(2))

if df["flood"].nunique() < 2:
    raise RuntimeError("The sampled dataset contains only one class; cannot train a classifier.")

if int(df["flood"].sum()) < 10:
    raise RuntimeError(
        "Too few flood samples for a meaningful train/test split. "
        "Review the flood inventory, masks, sampling scale, and study area."
    )

X = df[FEATURES]
y = df["flood"]

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.25,
    random_state=42,
    stratify=y,
)

rf = RandomForestClassifier(
    n_estimators=200,
    max_depth=15,
    class_weight="balanced",
    random_state=42,
    n_jobs=-1,
)

rf.fit(X_train, y_train)

y_prob = rf.predict_proba(X_test)[:, 1]
y_pred_05 = (y_prob >= 0.50).astype(int)
y_pred_selected = (y_prob >= CLASSIFICATION_THRESHOLD).astype(int)

print("\nRandom Forest evaluation at threshold 0.50")
print(confusion_matrix(y_test, y_pred_05))
print(classification_report(y_test, y_pred_05, zero_division=0))
print("ROC-AUC:", round(roc_auc_score(y_test, y_prob), 4))
print("PR-AUC:", round(average_precision_score(y_test, y_prob), 4))

print(f"\nEvaluation at selected threshold {CLASSIFICATION_THRESHOLD:.2f}")
print(confusion_matrix(y_test, y_pred_selected))
print(classification_report(y_test, y_pred_selected, zero_division=0))

# Save the trained scikit-learn model for reproducibility.
joblib.dump({"model": rf, "features": FEATURES}, MODEL_FILE)
print("Model saved:", MODEL_FILE)


# ---------------------------------------------------------------------
# 6. FEATURE IMPORTANCE
# ---------------------------------------------------------------------

print("\n[5/8] Calculating feature importance...")

importance = pd.DataFrame({
    "Feature": FEATURES,
    "Importance": rf.feature_importances_,
}).sort_values("Importance", ascending=False)

print(importance.to_string(index=False))

plt.figure(figsize=(8, 5))
plt.barh(
    importance.sort_values("Importance")["Feature"],
    importance.sort_values("Importance")["Importance"],
)
plt.xlabel("Feature importance")
plt.title("Random Forest - Jakarta Flood Susceptibility")
plt.tight_layout()
plt.show()


# ---------------------------------------------------------------------
# 7. EXPORT PREDICTOR RASTER AND DOWNLOAD FROM GOOGLE DRIVE
# ---------------------------------------------------------------------

print("\n[6/8] Exporting predictor raster to Google Drive...")

os.makedirs(f"/content/drive/MyDrive/{DRIVE_FOLDER}", exist_ok=True)

export_task = ee.batch.Export.image.toDrive(
    image=predictor_image,
    description="Jakarta_Flood_Predictors",
    folder=DRIVE_FOLDER,
    fileNamePrefix="Jakarta_predictors",
    region=JAKARTA,
    scale=SAMPLE_SCALE,
    maxPixels=1e13,
    fileFormat="GeoTIFF",
)

export_task.start()
print("Earth Engine export task started.")

# Wait for export to finish. This can take several minutes.
while True:
    status = export_task.status()
    state = status.get("state")
    print("Export status:", state)

    if state == "COMPLETED":
        break
    if state in ("FAILED", "CANCELLED"):
        raise RuntimeError(f"Earth Engine export did not complete: {status}")

    time.sleep(20)

print("Earth Engine export completed.")

print("Mounting Google Drive...")
drive.mount("/content/drive", force_remount=False)

if not os.path.exists(DRIVE_RASTER):
    raise FileNotFoundError(
        f"Export completed, but the expected file was not found: {DRIVE_RASTER}. "
        "Check the GeoAI_Jakarta folder in Google Drive."
    )

shutil.copy2(DRIVE_RASTER, PREDICTOR_RASTER)
print("Predictor raster copied to:", PREDICTOR_RASTER)


# ---------------------------------------------------------------------
# 8. APPLY THE TRAINED MODEL TO THE PREDICTOR RASTER
# ---------------------------------------------------------------------

print("\n[7/8] Generating flood probability and susceptibility GeoTIFFs...")

with rasterio.open(PREDICTOR_RASTER) as src:
    if src.count != len(FEATURES):
        raise ValueError(
            f"Expected {len(FEATURES)} raster bands in order {FEATURES}, "
            f"but found {src.count}. Check the exported raster band order."
        )

    raster_data = src.read().astype(np.float32)
    profile = src.profile.copy()
    band_masks = src.read_masks()

    rows, cols = raster_data.shape[1:]
    pixel_features = raster_data.reshape(len(FEATURES), -1).T
    pixel_valid = np.all(np.isfinite(pixel_features), axis=1)

    # Also exclude pixels masked in any predictor band.
    pixel_valid &= np.all(band_masks.reshape(len(FEATURES), -1) > 0, axis=0)

    if src.nodata is not None:
        pixel_valid &= np.all(pixel_features != src.nodata, axis=1)

    probability_flat = np.full(rows * cols, -9999.0, dtype=np.float32)

    # Predict in chunks to reduce memory use for larger rasters.
    valid_indices = np.flatnonzero(pixel_valid)
    chunk_size = 200_000

    for start in range(0, len(valid_indices), chunk_size):
        indices = valid_indices[start:start + chunk_size]
        probability_flat[indices] = rf.predict_proba(
            pixel_features[indices]
        )[:, 1].astype(np.float32)

    probability = probability_flat.reshape(rows, cols)

    probability_profile = profile.copy()
    probability_profile.update(
        count=1,
        dtype="float32",
        nodata=-9999.0,
        compress="lzw",
    )

    with rasterio.open(PROBABILITY_RASTER, "w", **probability_profile) as dst:
        dst.write(probability, 1)

print("Flood probability raster saved:", PROBABILITY_RASTER)

# Class definitions:
# 0 = NoData; 1 = Low; 2 = Moderate; 3 = High.
with rasterio.open(PROBABILITY_RASTER) as src:
    probability = src.read(1)
    profile = src.profile.copy()

valid = probability != -9999.0
susceptibility = np.zeros(probability.shape, dtype=np.uint8)

susceptibility[valid & (probability < CLASSIFICATION_THRESHOLD)] = 1
susceptibility[
    valid
    & (probability >= CLASSIFICATION_THRESHOLD)
    & (probability < 0.60)
] = 2
susceptibility[valid & (probability >= 0.60)] = 3

susceptibility_profile = profile.copy()
susceptibility_profile.update(
    count=1,
    dtype="uint8",
    nodata=0,
    compress="lzw",
)

with rasterio.open(SUSCEPTIBILITY_RASTER, "w", **susceptibility_profile) as dst:
    dst.write(susceptibility, 1)

print("Susceptibility GeoTIFF saved:", SUSCEPTIBILITY_RASTER)


# ---------------------------------------------------------------------
# 9. PLOT AND SAVE THE SUSCEPTIBILITY MAP
# ---------------------------------------------------------------------

print("\n[8/8] Creating the susceptibility map...")

from matplotlib.colors import ListedColormap
from matplotlib.patches import Patch

with rasterio.open(SUSCEPTIBILITY_RASTER) as src:
    susceptibility = src.read(1)
    bounds = src.bounds

# Mask NoData (0) so it is not displayed as a susceptibility class.
plot_data = np.ma.masked_equal(susceptibility, 0)
cmap = ListedColormap(["green", "yellow", "red"])

fig, ax = plt.subplots(figsize=(10, 8))
ax.imshow(
    plot_data,
    cmap=cmap,
    vmin=1,
    vmax=3,
    extent=[bounds.left, bounds.right, bounds.bottom, bounds.top],
    origin="upper",
)
ax.set_title("Jakarta Urban Flood Susceptibility (Exploratory)")
ax.set_xlabel("Longitude")
ax.set_ylabel("Latitude")

legend = [
    Patch(facecolor="green", label=f"Low (< {CLASSIFICATION_THRESHOLD:.2f})"),
    Patch(facecolor="yellow", label=f"Moderate ({CLASSIFICATION_THRESHOLD:.2f}–0.60)"),
    Patch(facecolor="red", label="High (≥ 0.60)"),
]
ax.legend(handles=legend, loc="upper right")
plt.tight_layout()
plt.savefig(MAP_PNG, dpi=300, bbox_inches="tight")
plt.show()

print("\nPROCESS COMPLETE")
print("Probability raster:    ", PROBABILITY_RASTER)
print("Susceptibility raster: ", SUSCEPTIBILITY_RASTER)
print("Map image:             ", MAP_PNG)
print("Trained model:         ", MODEL_FILE)

print(
    "\nScientific limitation: This is an exploratory susceptibility screening "
    "result. The Sentinel-2 composite is from 2025, while the flood inventory "
    "contains historical events. Random pixel-level validation can also "
    "overestimate generalization because nearby pixels may be spatially correlated. "
    "Verify the Global Flood Database observation masks and use spatially "
    "independent validation before making operational claims."
)